//! Assembly (README "装配:StrategySet 与 strategy_set!"): the `StrategySet` trait the engine is
//! generic over, `ResetPreview`, and the `strategy_set!` macro that generates the enums and the
//! static `match` dispatch.

use crate::StrategyDesc;
use crate::advice::AdviceOut;
use crate::ctx::{Ctx, SubsBuilder};
use crate::desc::CmdDesc;
use crate::event::EventRef;
use crate::group::GroupTable;
use crate::layout::ModelLayoutDesc;
use crate::params::ParamError;
use crate::snapshot::{RestoreError, SnapshotReader, SnapshotWriter};
use crate::strategy::{ModelParamEffect, SnapshotProgress, StrategyInstance};
use crate::views::{ModelViews, RefView, Views};

pub use crate::set_macro::reset_preview_of;

/// Structural-change preview of a `SetParams` (same names and widths as hft-event `CmdPreview`).
#[derive(Copy, Clone, Eq, PartialEq, Hash, Debug, Default)]
pub struct ResetPreview {
    /// Groups of the new table that restart empty (new GroupId, changed fingerprint or changed
    /// structural value).
    pub reset_groups: u32,
    /// max over those groups of the estimated no-open time (ms, saturating).
    pub no_open_ms: u32,
}

/// The set of strategy kinds linked into a binary; generated by `strategy_set!`. Every method is
/// one `match` plus an inlined call (static dispatch, no `dyn`). A `kind_id` outside the set:
/// `decode_params` → `SchemaMismatch{want: 0, got: kind_id}`, the static queries → empty values.
pub trait StrategySet: 'static {
    /// One variant per strategy kind.
    type Inst;
    type ModelInst;
    /// Decoded parameters (ctl-gateway → Mailbox → sequencer).
    type Params: Send;
    fn kinds() -> &'static [StrategyDesc];
    fn decode_params(
        kind_id: u16,
        body: &[u8],
        schema_ver: u16,
        g: &GroupTable,
    ) -> Result<Self::Params, ParamError>;
    fn validate_params(p: &Self::Params, g: &GroupTable, rd: &RefView<'_>) -> Result<(), ParamError>;
    fn create(
        i: StrategyInstance,
        p: &Self::Params,
        g: &GroupTable,
        rd: &RefView<'_>,
    ) -> Result<Self::Inst, ParamError>;
    fn create_model(
        i: StrategyInstance,
        p: &Self::Params,
        g: &GroupTable,
        rd: &RefView<'_>,
    ) -> Self::ModelInst;
    fn on_event<V: Views>(s: &mut Self::Inst, ev: &EventRef<'_>, v: &V, ctx: &mut Ctx<'_>);
    /// Parameters of another kind → `SchemaMismatch`.
    fn on_params(
        s: &mut Self::Inst,
        p: &Self::Params,
        g: &GroupTable,
        rd: &RefView<'_>,
    ) -> Result<(), ParamError>;
    fn subscriptions(s: &Self::Inst, g: &GroupTable, out: &mut SubsBuilder<'_>);
    fn snapshot(s: &Self::Inst, w: &mut SnapshotWriter);
    fn restore(s: &mut Self::Inst, r: &mut SnapshotReader<'_>) -> Result<(), RestoreError>;
    fn model_mem_bytes(p: &Self::Params, n_groups: u16) -> u64;
    fn model_snapshot_bytes(p: &Self::Params, n_groups: u16) -> u64;
    fn model_layout(kind_id: u16) -> &'static ModelLayoutDesc;
    fn model_on_event<V: ModelViews>(
        m: &mut Self::ModelInst,
        ev: &EventRef<'_>,
        v: &V,
        out: &mut AdviceOut<'_>,
    );
    fn model_on_params(
        m: &mut Self::ModelInst,
        p: &Self::Params,
        g: &GroupTable,
        rd: &RefView<'_>,
    ) -> ModelParamEffect;
    fn model_snapshot_chunk(
        m: &Self::ModelInst,
        from_gix: u16,
        w: &mut SnapshotWriter,
        max_bytes: u32,
    ) -> SnapshotProgress;
    fn model_restore(m: &mut Self::ModelInst, r: &mut SnapshotReader<'_>) -> Result<(), RestoreError>;
    /// `Model::PATH_VERSION` of the kind (outside the set → 0).
    fn model_path_version(kind_id: u16) -> u32;
    fn model_snapshot_path(m: &Self::ModelInst, w: &mut SnapshotWriter);
    fn model_restore_path(m: &mut Self::ModelInst, r: &mut SnapshotReader<'_>) -> Result<(), RestoreError>;
    fn model_path_settle_ms(p: &Self::Params) -> u64;
    /// ctl-gateway preview of a SetParams (cold), aligned by GroupId.
    fn reset_preview(
        old: &Self::Params,
        old_g: &GroupTable,
        new: &Self::Params,
        new_g: &GroupTable,
    ) -> ResetPreview;
    /// `params::schema_json(&DESC, Model::LAYOUT, schema.version)`; outside the set → `None`.
    #[cfg(feature = "schema-json")]
    fn schema_json(kind_id: u16) -> Option<String>;
    /// Strategy command descriptors; outside the set → empty.
    fn cmds(kind_id: u16) -> &'static [CmdDesc];
}
