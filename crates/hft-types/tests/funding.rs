//! Funding settlement time normalization (TYP-130).

use hft_types::funding_settle_norm_ns;

#[test]
fn typ_130_funding_norm() {
    let rows: [(&str, i64, u32, u32, i64); 13] = [
        (
            "TYP-130.1",
            1_791_100_800_003_000_000,
            28_800,
            0,
            1_791_100_800_000_000_000,
        ),
        (
            "TYP-130.2",
            1_791_100_799_990_000_000,
            28_800,
            0,
            1_791_100_800_000_000_000,
        ),
        (
            "TYP-130.3",
            1_791_086_400_000_000_000,
            28_800,
            0,
            1_791_072_000_000_000_000,
        ),
        (
            "TYP-130.4",
            1_791_086_400_000_000_001,
            28_800,
            0,
            1_791_100_800_000_000_000,
        ),
        (
            "TYP-130.5",
            1_791_086_399_999_999_999,
            28_800,
            0,
            1_791_072_000_000_000_000,
        ),
        (
            "TYP-130.6",
            1_791_100_800_003_000_000,
            0,
            0,
            1_791_100_800_003_000_000,
        ),
        (
            "TYP-130.7",
            1_791_108_600_000_000_000,
            3_600,
            1_800,
            1_791_109_800_000_000_000,
        ),
        (
            "TYP-130.8",
            1_791_100_800_003_000_000,
            28_800,
            32_400,
            1_791_104_400_000_000_000,
        ),
        ("TYP-130.9", -1, 28_800, 0, 0),
        ("TYP-130.10", -14_400_000_000_000, 28_800, 0, -28_800_000_000_000),
        ("TYP-130.11", i64::MAX, 28_800, 0, 9_223_344_000_000_000_000),
        ("TYP-130.12", i64::MIN, 28_800, 0, -9_223_344_000_000_000_000),
        ("TYP-130.13", 0, 4_294_967_295, 4_294_967_295, 0),
    ];
    for (row, ts, iv, an, want) in rows {
        assert_eq!(funding_settle_norm_ns(ts, iv, an), want, "{row}");
    }
}
