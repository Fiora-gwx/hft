/// Φ(z) × 1e9 for z × 1e9 (saturates beyond |z| = 5).
pub fn cdf(z: i64) -> i64 {
    let a = i128::from(z).abs();
    let pos = a * i128::from(STEPS);
    let k = pos / i128::from(ONE);
    let frac = pos % i128::from(ONE);
    let last = (PHI.len() - 1) as i128;
    let v = if k >= last {
        i128::from(PHI[PHI.len() - 1])
    } else {
        let lo = i128::from(PHI[k as usize]);
        let hi = i128::from(PHI[k as usize + 1]);
        lo + (hi - lo) * frac / i128::from(ONE)
    };
    let v = v as i64;
    if z < 0 { ONE - v } else { v }
}

/// z × 1e9 with Φ(z) = p (p × 1e9, clamped to [0.001, 0.999]).
pub fn inv_cdf(p: i64) -> i64 {
    let p = p.clamp(ONE / 1000, ONE - ONE / 1000);
    let (q, neg) = if p < ONE / 2 { (ONE - p, true) } else { (p, false) };
    // Largest k with PHI[k] <= q, then interpolate within [k, k + 1].
    let k = PHI.partition_point(|&v| v <= q).saturating_sub(1);
    let z = if k + 1 >= PHI.len() {
        k as i64 * ONE / STEPS
    } else {
        let (lo, hi) = (PHI[k], PHI[k + 1]);
        let frac = if hi > lo {
            i128::from(q - lo) * i128::from(ONE) / i128::from(hi - lo)
        } else {
            0
        };
        ((i128::from(k as i64) * i128::from(ONE) + frac) / i128::from(STEPS)) as i64
    };
    if neg { -z } else { z }
}
