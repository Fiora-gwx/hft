/// What is remembered of each recent record (possible triggers of later samples).
#[derive(Copy, Clone, Debug, Default)]
struct TrigInfo {
    seq: u64,
    tsc: u64,
    kind: u16,
    sub: u8,
    inst: u32,
}

/// Recent records by seq (direct-mapped; a sample whose trigger fell out is `unresolved`).
const TRIG_RING: usize = 1 << 16;

#[derive(Clone, Debug)]
struct TrigRing {
    v: Vec<TrigInfo>,
}

impl TrigRing {
    fn new() -> TrigRing {
        TrigRing {
            v: vec![TrigInfo::default(); TRIG_RING],
        }
    }
    fn put(&mut self, t: TrigInfo) {
        self.v[(t.seq as usize) & (TRIG_RING - 1)] = t;
    }
    fn get(&self, seq: u64) -> Option<TrigInfo> {
        let t = self.v[(seq as usize) & (TRIG_RING - 1)];
        (t.seq == seq && t.kind != 0).then_some(t)
    }
}

/// A sample waiting for the `ClockStatus` after it.
#[derive(Copy, Clone, Debug)]
struct Pending {
    s: LatencySample,
    trig_sub: u8,
    inst: u32,
    /// Trigger record `proc_tsc` for `leg_gap` (second legs).
    leg_tsc: Option<u64>,
    /// TSC whose interpolation interval is used (`rx_tsc`, else `sent_tsc`).
    anchor: u64,
    /// Latest TSC point that must be covered by a `ClockStatus`.
    need: u64,
}

/// Reads `T` from the start of `body`, zero-extending shorter (older-version) bodies.
pub(crate) fn read_body<T: FromBytes>(body: &[u8]) -> Option<T> {
    let n = size_of::<T>();
    if body.len() >= n {
        return T::read_from_prefix(body).ok().map(|(t, _)| t);
    }
    let mut buf = vec![0u8; n];
    buf[..body.len()].copy_from_slice(body);
    T::read_from_bytes(&buf).ok()
}

/// Journal-fed accumulator (README "使用本组件"; M1.5 part).
#[derive(Debug)]
pub struct Telemetry {
    cfg: TelemetryConfig,
    insts: Vec<InstClass>,
    accts: Vec<AcctKind>,
    cal: CalQueue,
    ring: TrigRing,
    pending: VecDeque<Pending>,
    hist: SeriesSet<HistKey>,
    cal_err: SeriesSet<HistKey>,
    win_counters: BTreeMap<CounterKey, u64>,
    day_counters: BTreeMap<CounterKey, u64>,
    win_start: Option<i64>,
    trust: ClockTrust,
    hz_milli: u64,
}

impl Telemetry {
    pub fn new(cfg: &TelemetryConfig, rd: &RefData, _cat: &StrategyCatalog) -> Telemetry {
        let insts = (0..rd.inst_count() as u32 + 1)
            .map(|i| inst_class(rd, InstId(i)))
            .collect();
        let accts = (0..=u8::MAX).map(|a| acct_kind(rd, AccountId(a))).collect();
        let p = cfg.hist_params();
        Telemetry {
            cfg: *cfg,
            insts,
            accts,
            cal: CalQueue::default(),
            ring: TrigRing::new(),
            pending: VecDeque::new(),
            hist: SeriesSet::new(p, cfg.max_series),
            cal_err: SeriesSet::new(p, cfg.max_series),
            win_counters: BTreeMap::new(),
            day_counters: BTreeMap::new(),
            win_start: None,
            trust: ClockTrust::Trusted,
            hz_milli: 0,
        }
    }

    /// Pure function: time points → segments with the per-sample error bound.
    pub fn stages(s: &LatencySample, cal: &ClockCal) -> StageSet {
        stages::stages(s, cal)
    }

    /// The calibration queue (≤ `CAL_QUEUE_MAX` most recent `ClockStatus`).
    pub fn cal_queue(&self) -> &CalQueue {
        &self.cal
    }

    /// Feeds one seq-journal record (multi-part records reassembled: `body` = logical body).
    pub fn ingest(&mut self, hdr: &RecordHeader, body: &[u8]) {
        let kind = EventKind(hdr.kind);
        let mut t = TrigInfo {
            seq: hdr.seq,
            tsc: hdr.tsc,
            kind: hdr.kind,
            sub: 0,
            inst: 0,
        };
        if is_market_kind(kind) {
            if let Some(h) = read_body::<MarketHdr>(body) {
                t.inst = h.inst.0;
            }
        } else if kind == EventKind::ORDER_EVENT {
            // OrderEvent: `what` @ 2, `inst` @ 12 (hft-event layout).
            if let (Some(&what), Some(inst)) = (body.get(2), body.get(12..16)) {
                t.sub = what;
                t.inst = u32::from_le_bytes([inst[0], inst[1], inst[2], inst[3]]);
            }
        }
        self.ring.put(t);
        match kind {
            EventKind::CLOCK_STATUS => {
                if let Some(c) = read_body::<ClockStatus>(body) {
                    let row = ClockStatusRow::from(&c);
                    if row.tsc_hz_milli != 0 {
                        self.hz_milli = row.tsc_hz_milli;
                    }
                    self.cal.push(row);
                    self.drain(false);
                }
            }
            EventKind::HOST_PROFILE => {
                if let Some(h) = read_body::<HostProfile>(body)
                    && h.tsc_hz_milli != 0
                {
                    self.hz_milli = h.tsc_hz_milli;
                }
            }
            EventKind::LATENCY_SAMPLE => {
                if let Some(s) = read_body::<LatencySample>(body) {
                    self.push_sample(s);
                }
            }
            _ => {}
        }
    }

    fn push_sample(&mut self, mut s: LatencySample) {
        let trig = self.ring.get(s.trigger_seq);
        if s.trigger_kind == 0
            && let Some(t) = trig
        {
            s.trigger_kind = t.kind;
        }
        let class = trigger_class(EventKind(s.trigger_kind));
        let rx_based = class != TriggerClass::Other && s.rx_tsc.0 != 0;
        let anchor = if rx_based { s.rx_tsc.0 } else { s.sent_tsc.0 };
        let need = [s.rx_tsc.0, s.proc_tsc.0, s.decided_tsc.0, s.sent_tsc.0]
            .into_iter()
            .max()
            .unwrap_or(0);
        let p = Pending {
            s,
            trig_sub: trig.map_or(0, |t| {
                if t.kind == EventKind::ORDER_EVENT.0 {
                    t.sub
                } else {
                    0
                }
            }),
            inst: trig.map_or(0, |t| t.inst),
            leg_tsc: trig.map(|t| t.tsc),
            anchor,
            need,
        };
        // Computable now when its points are already covered (late samples); otherwise it waits
        // for the next `ClockStatus` (only a new row can complete an interval).
        match self.resolve(&p, false) {
            Some(cal) => self.process(&p, cal),
            None => self.pending.push_back(p),
        }
    }

    /// The calibration of a pending sample: `None` = wait; `Some(None)` = no interval will ever
    /// exist (computed without one).
    fn resolve(&self, p: &Pending, end: bool) -> Option<Option<ClockCal>> {
        let last = self.cal.last().map_or(0, |r| r.tsc);
        match self.cal.bracket(p.anchor, self.cfg.cal_max_err_ns) {
            Br::Cal(c) if last >= p.need => Some(Some(c)),
            Br::Cal(_) | Br::Wait if !end => None,
            Br::Cal(c) => Some(Some(c)),
            Br::Wait => Some(self.cal.open_tail(self.cfg.cal_max_err_ns)),
            Br::None => Some(None),
        }
    }

    /// Computes every pending sample whose interval is complete; `end` = journal ended (the rest
    /// is computed without the next `ClockStatus` and counted `unsynced_cal`).
    fn drain(&mut self, end: bool) {
        if self.pending.is_empty() {
            return;
        }
        let mut keep = VecDeque::with_capacity(self.pending.len());
        while let Some(p) = self.pending.pop_front() {
            match self.resolve(&p, end) {
                Some(cal) => self.process(&p, cal),
                None => keep.push_back(p),
            }
        }
        self.pending = keep;
    }

    /// Ends the journal: samples still waiting for their next `ClockStatus` are computed without
    /// it and counted `unsynced_cal` (README "时钟校准序列").
    pub fn finish(&mut self) {
        self.drain(true);
    }

    fn count(&mut self, name: CounterName, stage: Option<Stage>, venue: VenueId, ts_src: TsSrc) {
        let k = CounterKey {
            name,
            stage,
            venue,
            ts_src,
        };
        *self.win_counters.entry(k).or_insert(0) += 1;
        *self.day_counters.entry(k).or_insert(0) += 1;
    }

    fn process(&mut self, p: &Pending, cal: Option<ClockCal>) {
        let s = &p.s;
        // Without any calibration row the nominal frequency (HostProfile / ClockStatus) still
        // converts the pure TSC segments.
        let cal = cal.unwrap_or_else(|| {
            ClockCal::new(
                None,
                ClockStatusRow {
                    tsc_hz_milli: self.hz_milli,
                    ..ClockStatusRow::default()
                },
                None,
                self.cfg.cal_max_err_ns,
            )
        });
        let mut st = stages::stages(s, &cal);
        if s.link_role == LINK_SECOND {
            st.set(Stage::LegGap, p.leg_tsc.map(|t| cal.tsc_ns(t, s.sent_tsc.0)));
        }
        let key = HistKey {
            stage: Stage::KernelRx,
            dataset: self.cfg.dataset,
            venue: s.venue,
            account: s.account,
            account_kind: self
                .accts
                .get(usize::from(s.account.0))
                .copied()
                .unwrap_or(AcctKind::Unknown),
            inst_class: self
                .insts
                .get(p.inst as usize)
                .copied()
                .unwrap_or(InstClass::Unknown),
            action: s.action,
            strategy: s.strategy,
            trigger_kind: EventKind(s.trigger_kind),
            trigger_sub: p.trig_sub,
            ts_src: st.ts_src,
            other: false,
        };
        let (venue, ts_src) = (s.venue, st.ts_src);
        if !st.cal_ok {
            self.count(CounterName::UnsyncedCal, None, venue, ts_src);
        }
        if cal.b.is_some() {
            let ds = self.cfg.dataset;
            if self.cal_err.record(
                key,
                |_| HistKey::other(Stage::KernelRx, ds),
                i64::from(st.err_bound_ns),
            ) {
                self.count(CounterName::SeriesOverflow, Some(Stage::KernelRx), venue, ts_src);
            }
        }
        let ex_bad = i64::from(st.ex_offset_ns) > self.cfg.clock_untrusted_offset_ns;
        for stage in Stage::ALL {
            match st.get(stage) {
                None => {
                    if st.is_missing(stage) {
                        self.count(CounterName::Missing, Some(stage), venue, ts_src);
                    }
                }
                Some(_) if stage.cross_domain() && !st.cal_ok => {}
                Some(_) if stage.exchange_clock() && ex_bad => {
                    self.trust = ClockTrust::Untrusted;
                    self.count(CounterName::Unsynced, Some(stage), venue, ts_src);
                }
                Some(v) if v < 0 => self.count(CounterName::Negative, Some(stage), venue, ts_src),
                Some(v) => {
                    let ds = self.cfg.dataset;
                    if self
                        .hist
                        .record(key.with_stage(stage), |k| HistKey::other(k.stage, ds), v)
                    {
                        self.count(CounterName::SeriesOverflow, Some(stage), venue, ts_src);
                    }
                }
            }
        }
    }

    /// Window roll (README "直方图"): windows are aligned to multiples of `window_s` in UTC; the
    /// first call opens the window containing `now`; when `now` reaches the window end the window
    /// is returned and the window containing `now` is opened.
    pub fn window(&mut self, now_utc_ns: i64) -> Option<WindowReport> {
        let w = i64::from(self.cfg.window_s.max(1)) * 1_000_000_000;
        let start = *self.win_start.get_or_insert(now_utc_ns.div_euclid(w) * w);
        if now_utc_ns < start + w {
            return None;
        }
        self.win_start = Some(now_utc_ns.div_euclid(w) * w);
        let trust = std::mem::replace(&mut self.trust, ClockTrust::Trusted);
        Some(WindowReport {
            start_ns: start,
            end_ns: start + w,
            hist: self.hist.take_window(),
            cal_err: self.cal_err.take_window(),
            counters: std::mem::take(&mut self.win_counters).into_iter().collect(),
            clock_trust: trust,
        })
    }

    /// UTC day close: the daily accumulation of every series and counter, then reset.
    pub fn day_close(&mut self, day: u32) -> DailyClose {
        DailyClose {
            day,
            hist: self.hist.take_day(),
            cal_err: self.cal_err.take_day(),
            counters: std::mem::take(&mut self.day_counters).into_iter().collect(),
        }
    }
}

fn inst_class(rd: &RefData, id: InstId) -> InstClass {
    let r = rd.inst(id);
    if id.0 == 0 || r.status == InstStatus::Invalid {
        return InstClass::Unknown;
    }
    match r.kind {
        InstKind::Spot => InstClass::Spot,
        InstKind::Perp => InstClass::Perp,
        _ => InstClass::Unknown,
    }
}

fn acct_kind(rd: &RefData, a: AccountId) -> AcctKind {
    let m = rd.account(a);
    if a.0 == 0 || m.id != a {
        return AcctKind::Unknown;
    }
    match m.kind {
        AccountKind::Live => AcctKind::Live,
        AccountKind::Sim(_) => AcctKind::Sim,
    }
}
