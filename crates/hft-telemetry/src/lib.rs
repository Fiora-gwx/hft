/// Configuration (README "使用本组件"). `max_series`, `cal_max_err_ns` and `naked_usd` are given by
/// the caller (`Default` leaves them 0).
#[derive(Copy, Clone, Debug, Eq, PartialEq)]
pub struct TelemetryConfig {
    pub window_s: u32,
    pub sig_digits: u8,
    pub min_ns: u64,
    pub max_ns: u64,
    /// Cardinality limit of the histogram keys; later new keys go to `other`.
    pub max_series: u32,
    /// Exchange-clock segments are trusted only while both `ClockStatus.max_error_ns` ≤ this.
    pub clock_untrusted_offset_ns: i64,
    /// latency-budget §2.1 threshold of the per-sample error bound.
    pub cal_max_err_ns: u32,
    pub naked_usd: Notional,
    /// Dataset label of everything this instance computes (never merged across datasets).
    pub dataset: Dataset,
}

impl Default for TelemetryConfig {
    fn default() -> Self {
        TelemetryConfig {
            window_s: 10,
            sig_digits: 3,
            min_ns: 1,
            max_ns: 10_000_000_000,
            max_series: 0,
            clock_untrusted_offset_ns: 200_000,
            cal_max_err_ns: 0,
            naked_usd: Notional(0),
            dataset: Dataset::Live,
        }
    }
}

impl TelemetryConfig {
    fn hist_params(&self) -> HistParams {
        HistParams {
            sig_digits: self.sig_digits,
            min_ns: self.min_ns,
            max_ns: self.max_ns,
        }
    }
}

/// Data sets that are never merged (README "直方图"; latency-budget §5). Sim accounts are a
/// separate dataset through `HistKey.account_kind`; HW/SW through `HistKey.ts_src`.
#[derive(Copy, Clone, Debug, Eq, PartialEq, Ord, PartialOrd, Hash, Serialize, Default)]
pub enum Dataset {
    /// Production journal (live tailing or the day's journal).
    #[default]
    Live,
    /// Verification replay (`replayer verify`).
    VerifyReplay,
    /// Simulated re-run (`replayer sim`).
    SimReplay,
    /// Mock loop-back.
    MockLoop,
    /// Event-weighted offline statistics (`event_weighted`).
    EventWeighted,
}

