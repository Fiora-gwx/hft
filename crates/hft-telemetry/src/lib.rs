/// Errors of the offline functions.
#[derive(Clone, Debug, Eq, PartialEq)]
pub enum TelemetryError {
    /// The journal has a gap (reader `Next::Gap`).
    Gap(String),
    /// The reader failed (`Next::Err`).
    Read(String),
}

impl std::fmt::Display for TelemetryError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            TelemetryError::Gap(g) => write!(f, "journal gap: {g}"),
            TelemetryError::Read(e) => write!(f, "journal read error: {e}"),
        }
    }
}

