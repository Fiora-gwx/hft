/// Histogram key (README "直方图"). `trigger_sub` = the trigger `OrderEvent.what` for report
/// triggers (`rep_to_order` by report kind, latency-budget §5), 0 otherwise. `other` = the merged
/// series of keys beyond `max_series` (only `stage` and `dataset` kept).
#[derive(Copy, Clone, Debug, Eq, PartialEq, Ord, PartialOrd, Hash)]
pub struct HistKey {
    pub stage: Stage,
    pub dataset: Dataset,
    pub venue: VenueId,
    pub account: AccountId,
    pub account_kind: AcctKind,
    pub inst_class: InstClass,
    pub action: u8,
    pub strategy: StrategyId,
    pub trigger_kind: EventKind,
    pub trigger_sub: u8,
    pub ts_src: TsSrc,
    pub other: bool,
}

impl HistKey {
    /// The `other` series of `stage`.
    pub fn other(stage: Stage, dataset: Dataset) -> HistKey {
        HistKey {
            stage,
            dataset,
            venue: VenueId(0),
            account: AccountId(0),
            account_kind: AcctKind::Unknown,
            inst_class: InstClass::Unknown,
            action: 0,
            strategy: StrategyId(0),
            trigger_kind: EventKind(0),
            trigger_sub: 0,
            ts_src: TsSrc::Missing,
            other: true,
        }
    }

    /// Same key with another stage.
    pub fn with_stage(mut self, stage: Stage) -> HistKey {
        self.stage = stage;
        self
    }
}

