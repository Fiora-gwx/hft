//! Permission table: the hft-ctl-proto README table "权限表" must equal the rows rendered from
//! `crates/hft-ctl-proto/src/perms.rs` (`PERM_ROWS[*].text`, then `OPTIONAL_ROWS`), row by row
//! (crates/hft-ctl-proto/TESTS.md CTP-093). Absent files (fixture trees) → no check.

use std::path::Path;

use syn::{Expr, Item, Lit};

/// README holding the table.
pub const PERM_README: &str = "crates/hft-ctl-proto/README.md";
/// Code holding the rows.
pub const PERM_CODE: &str = "crates/hft-ctl-proto/src/perms.rs";

fn strs(e: &Expr) -> Option<Vec<String>> {
    let Expr::Array(a) = e else { return None };
    a.elems
        .iter()
        .map(|x| match x {
            Expr::Lit(l) => match &l.lit {
                Lit::Str(s) => Some(s.value()),
                _ => None,
            },
            _ => None,
        })
        .collect()
}

fn unref(e: &Expr) -> &Expr {
    match e {
        Expr::Reference(r) => unref(&r.expr),
        Expr::Paren(p) => unref(&p.expr),
        _ => e,
    }
}

/// Markdown rows rendered from the code (`| c1 | … | c9 |`).
pub fn code_rows(src: &str) -> Result<Vec<String>, String> {
    let file = syn::parse_file(src).map_err(|e| format!("{PERM_CODE}: {e}"))?;
    let mut core = None;
    let mut optional = None;
    for item in &file.items {
        let Item::Const(c) = item else { continue };
        let Expr::Array(a) = unref(&c.expr) else { continue };
        if c.ident == "PERM_ROWS" {
            let mut rows = Vec::new();
            for e in &a.elems {
                let Expr::Struct(s) = e else {
                    return Err(format!("{PERM_CODE}: PERM_ROWS element is not a PermRow literal"));
                };
                let text = s
                    .fields
                    .iter()
                    .find(|f| matches!(&f.member, syn::Member::Named(n) if n == "text"))
                    .and_then(|f| strs(&f.expr))
                    .ok_or_else(|| format!("{PERM_CODE}: a PermRow has no literal `text` array"))?;
                rows.push(text);
            }
            core = Some(rows);
        } else if c.ident == "OPTIONAL_ROWS" {
            optional = Some(
                a.elems
                    .iter()
                    .map(|e| {
                        strs(e).ok_or_else(|| {
                            format!("{PERM_CODE}: OPTIONAL_ROWS element is not a string array")
                        })
                    })
                    .collect::<Result<Vec<_>, _>>()?,
            );
        }
    }
    let core = core.ok_or_else(|| format!("{PERM_CODE}: const PERM_ROWS not found"))?;
    let optional = optional.unwrap_or_default();
    Ok(core
        .into_iter()
        .chain(optional)
        .map(|cells| format!("| {} |", cells.join(" | ")))
        .collect())
}

/// Rows of the README table under "### 权限表" (header and separator excluded).
pub fn readme_rows(text: &str) -> Result<Vec<String>, String> {
    let start = text
        .find("\n### 权限表")
        .ok_or_else(|| format!("{PERM_README}: heading ### 权限表 not found"))?;
    let mut rows = Vec::new();
    let mut in_table = false;
    for line in text[start..].lines().skip(2) {
        let l = line.trim_end();
        if !in_table {
            if l.starts_with("| 命令 / 参数组合 |") {
                in_table = true;
            } else if l.starts_with("### ") {
                break;
            }
            continue;
        }
        if !l.starts_with('|') {
            break;
        }
        if l.starts_with("|---") {
            continue;
        }
        rows.push(l.to_string());
    }
    if !in_table {
        return Err(format!(
            "{PERM_README}: permission table not found under ### 权限表"
        ));
    }
    Ok(rows)
}

/// Compares the two lists; problems name the differing rows.
pub fn compare(readme: &[String], code: &[String]) -> Vec<String> {
    let mut out = Vec::new();
    for r in code {
        if !readme.contains(r) {
            out.push(format!(
                "{PERM_README}: permission row missing or different from {PERM_CODE}: {r}"
            ));
        }
    }
    for r in readme {
        if !code.contains(r) {
            out.push(format!(
                "{PERM_README}: permission row not generated by {PERM_CODE}: {r}"
            ));
        }
    }
    if out.is_empty() && readme != code {
        out.push(format!(
            "{PERM_README}: permission rows are in a different order than {PERM_CODE}"
        ));
    }
    out
}

/// The check over a tree; files absent → no problems.
pub fn check(root: &Path) -> Vec<String> {
    let (Ok(md), Ok(src)) = (
        std::fs::read_to_string(root.join(PERM_README)),
        std::fs::read_to_string(root.join(PERM_CODE)),
    ) else {
        return Vec::new();
    };
    let readme = match readme_rows(&md) {
        Ok(r) => r,
        Err(e) => return vec![e],
    };
    let code = match code_rows(&src) {
        Ok(r) => r,
        Err(e) => return vec![e],
    };
    compare(&readme, &code)
}
