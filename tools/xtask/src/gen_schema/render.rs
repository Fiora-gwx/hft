/// `L2Delta` → `l2_delta`.
pub fn snake(name: &str) -> String {
    let c: Vec<char> = name.chars().collect();
    let mut s = String::new();
    for (i, ch) in c.iter().enumerate() {
        if ch.is_ascii_uppercase() && i > 0 {
            let prev = c[i - 1];
            let next_lower = c.get(i + 1).is_some_and(|n| n.is_ascii_lowercase());
            if prev.is_ascii_lowercase() || prev.is_ascii_digit() || (prev.is_ascii_uppercase() && next_lower)
            {
                s.push('_');
            }
        }
        s.push(ch.to_ascii_lowercase());
    }
    s
}

/// Arrow schema file of a kind, relative to the repo root.
pub fn arrow_path(kind_name: &str) -> String {
    format!("{ARROW_DIR}/{}.json", snake(kind_name))
}

fn all_kinds(m: &Model) -> Vec<(&KindRow, bool)> {
    let mut v: Vec<(&KindRow, bool)> = m.kinds.iter().map(|k| (k, false)).collect();
    if let Some(e) = &m.ext_kinds {
        v.extend(e.iter().map(|k| (k, true)));
    }
    v.sort_by_key(|(k, _)| k.kind);
    v
}

// ---------- Python dtypes

fn uint(w: u16) -> &'static str {
    match w {
        1 => "<u1",
        2 => "<u2",
        4 => "<u4",
        _ => "<u8",
    }
}

fn py_str(s: &str) -> String {
    format!("\"{}\"", s.replace('\\', "\\\\").replace('"', "\\\""))
}

fn py_format(ty: &Ty, enums: &BTreeMap<String, EnumTable>) -> String {
    match ty {
        Ty::U8 => "\"<u1\"".into(),
        Ty::U16 => "\"<u2\"".into(),
        Ty::U32 => "\"<u4\"".into(),
        Ty::U64 => "\"<u8\"".into(),
        Ty::I8 => "\"<i1\"".into(),
        Ty::I16 => "\"<i2\"".into(),
        Ty::I32 => "\"<i4\"".into(),
        Ty::I64 => "\"<i8\"".into(),
        Ty::Px => "_t(\"<i8\", \"px\")".into(),
        Ty::Qty => "_t(\"<i8\", \"qty\")".into(),
        Ty::Notional => "_t(\"<i8\", \"notional\")".into(),
        Ty::Rate => "_t(\"<i8\", \"rate\")".into(),
        Ty::Tsc => "_t(\"<u8\", \"tsc\")".into(),
        Ty::UtcNs => "_t(\"<i8\", \"utc_ns\")".into(),
        Ty::Id(k, w) => format!("_t(\"{}\", \"id:{k}\")", uint(*w)),
        Ty::Enum(n) | Ty::Bits(n) => {
            let w = enums.get(n).map_or(1, |e| e.width as u16);
            let what = if matches!(ty, Ty::Enum(_)) { "enum" } else { "bits" };
            format!("_t(\"{}\", \"{what}:{n}\")", uint(w))
        }
        Ty::Bytes(n) => format!("\"({n},)u1\""),
        Ty::Pad(n) => format!("\"V{n}\""),
        Ty::Nested(f) => py_struct(f, ty.width(enums), enums),
    }
}

fn py_struct(fields: &[Field], size: u16, enums: &BTreeMap<String, EnumTable>) -> String {
    let names: Vec<String> = fields.iter().map(|f| py_str(&f.name)).collect();
    let formats: Vec<String> = fields.iter().map(|f| py_format(&f.ty, enums)).collect();
    let offsets: Vec<String> = fields.iter().map(|f| f.offset.to_string()).collect();
    format!(
        "_s([{}], [{}], [{}], {size})",
        names.join(", "),
        formats.join(", "),
        offsets.join(", ")
    )
}

/// FNV-1a 64 over `(kind u16, schema_version u16, size u32)` little-endian of the production kinds
/// (`m.kinds`, number order); the value `hft_py.schema_hash()` computes from its compiled table.
pub fn schema_hash(m: &Model) -> u64 {
    let mut h: u64 = 0xcbf2_9ce4_8422_2325;
    for k in &m.kinds {
        let mut b = Vec::with_capacity(8);
        b.extend_from_slice(&k.kind.to_le_bytes());
        b.extend_from_slice(&k.schema_version.to_le_bytes());
        b.extend_from_slice(&u32::from(k.layout.size()).to_le_bytes());
        for x in b {
            h ^= u64::from(x);
            h = h.wrapping_mul(0x0000_0100_0000_01b3);
        }
    }
    h
}

/// `python/_generated/events.py`.
pub fn events_py(m: &Model) -> String {
    let mut s = String::new();
    s += "# Generated by `cargo xtask gen-schema`; do not edit.\n";
    s += "# Source: crates/hft-event (schema::catalog); rules: crates/hft-event/README.md#实现说明\n";
    s += "\"\"\"numpy dtypes of every event kind (body / Var-Multi prefix), container structs and code tables.\"\"\"\n\n";
    s += "import numpy as np\n\n\n";
    s += "def _t(base, hft_type):\n    return np.dtype(base, metadata={\"hft.type\": hft_type})\n\n\n";
    s += "def _s(names, formats, offsets, itemsize):\n";
    s += "    return np.dtype({\"names\": names, \"formats\": formats, \"offsets\": offsets, \"itemsize\": itemsize})\n\n\n";
    s += "# Kind numbers.\n";
    for (k, _) in all_kinds(m) {
        let _ = writeln!(s, "KIND_{} = 0x{:04X}", snake(&k.name).to_uppercase(), k.kind);
    }
    s += "\n# Body (Fixed) or prefix (Var/Multi) dtypes; itemsize = size or prefix.\n";
    for (k, _) in all_kinds(m) {
        let _ = writeln!(
            s,
            "{} = {}",
            snake(&k.name).to_uppercase(),
            py_struct(&k.fields, k.layout.size(), &m.enums)
        );
    }
    s += "\n# Container and framing structs.\n";
    for st in &m.structs {
        let _ = writeln!(
            s,
            "{} = {}",
            snake(&st.name).to_uppercase(),
            py_struct(&st.fields, st.size, &m.enums)
        );
    }
    s += "\n# kind number -> (name, schema_version, layout, dtype).\nKINDS = {\n";
    for (k, _) in all_kinds(m) {
        let _ = writeln!(
            s,
            "    0x{:04X}: ({}, {}, {}, {}),",
            k.kind,
            py_str(&k.name),
            k.schema_version,
            py_str(&k.layout.text()),
            snake(&k.name).to_uppercase()
        );
    }
    s += "}\n\n";
    s += "# FNV-1a 64 of (kind u16, schema_version u16, size u32) LE of every production kind in number\n";
    s += "# order (size = fixed body or Var/Multi prefix); equals hft_py.schema_hash().\n";
    let _ = writeln!(s, "SCHEMA_HASH = 0x{:016X}", schema_hash(m));
    s += "\nSTRUCTS = {\n";
    for st in &m.structs {
        let _ = writeln!(s, "    {}: {},", py_str(&st.name), snake(&st.name).to_uppercase());
    }
    s += "}\n\n# Code tables and bit sets: name -> {value: item name}.\nENUMS = {\n";
    for e in m.enums.values() {
        let items: Vec<String> = e
            .items
            .iter()
            .map(|i| format!("{}: {}", i.value, py_str(&i.name)))
            .collect();
        let _ = writeln!(s, "    {}: {{{}}},", py_str(&e.name), items.join(", "));
    }
    s += "}\n\n# CmdKind number -> name.\nCMD_KINDS = {\n";
    for c in &m.cmd_kinds {
        let _ = writeln!(s, "    0x{:04X}: {},", c.value, py_str(&c.name));
    }
    s += "}\n";
    s
}

fn rdb_format(name: &str, ty: &str) -> String {
    let t = ty.replace(' ', "");
    match t.as_str() {
        "u8" => "\"<u1\"".into(),
        "u16" => "\"<u2\"".into(),
        "u32" => "\"<u4\"".into(),
        "u64" => "\"<u8\"".into(),
        "i8" => "\"<i1\"".into(),
        "i16" => "\"<i2\"".into(),
        "i32" => "\"<i4\"".into(),
        "i64" => "\"<i8\"".into(),
        "StrRef" => "STR_REF".into(),
        _ => {
            let n = t
                .strip_prefix("[u8;")
                .and_then(|r| r.strip_suffix(']'))
                .and_then(|n| n.parse::<u16>().ok())
                .unwrap_or(0);
            if name.starts_with("_pad") {
                format!("\"V{n}\"")
            } else {
                format!("\"({n},)u1\"")
            }
        }
    }
}

/// `python/_generated/refdata.py`.
pub fn refdata_py(m: &Model) -> String {
    let mut s = String::new();
    s += "# Generated by `cargo xtask gen-schema`; do not edit.\n";
    s += "# Source: crates/hft-refdata (schema::RDB1_ROWS, LoadErrCode); read-only parsing (the encoder is Rust only).\n";
    s += "\"\"\"numpy dtypes of the RDB1 rows and the LoadErrCode table.\"\"\"\n\n";
    s += "import numpy as np\n\n\n";
    s += "def _s(names, formats, offsets, itemsize):\n";
    s += "    return np.dtype({\"names\": names, \"formats\": formats, \"offsets\": offsets, \"itemsize\": itemsize})\n\n\n";
    let mut rows = m.rdb_rows.clone();
    // StrRef first: other rows reference it.
    rows.sort_by_key(|r| r.name != "StrRef");
    for r in &rows {
        let names: Vec<String> = r.fields.iter().map(|f| py_str(&f.0)).collect();
        let formats: Vec<String> = r.fields.iter().map(|f| rdb_format(&f.0, &f.3)).collect();
        let offsets: Vec<String> = r.fields.iter().map(|f| f.1.to_string()).collect();
        let _ = writeln!(
            s,
            "{} = _s([{}], [{}], [{}], {})",
            snake(&r.name).to_uppercase(),
            names.join(", "),
            formats.join(", "),
            offsets.join(", "),
            r.size
        );
    }
    s += "\n# RDB1 section -> (row name, row version, dtype).\nROWS = {\n";
    for r in m.rdb_rows.iter() {
        let _ = writeln!(
            s,
            "    {}: ({}, {}, {}),",
            r.section,
            py_str(&r.name),
            r.row_ver,
            snake(&r.name).to_uppercase()
        );
    }
    s += "}\n\n# LoadErrCode value -> name.\nLOAD_ERR_CODE = {\n";
    for c in &m.load_err {
        let _ = writeln!(s, "    {}: {},", c.value, py_str(&c.name));
    }
    s += "}\n";
    s
}

// ---------- Arrow

fn arrow_type(ty: &Ty, enums: &BTreeMap<String, EnumTable>) -> (String, Option<String>) {
    let u = |w: u16| format!("UInt{}", w * 8);
    match ty {
        Ty::U8 => ("UInt8".into(), None),
        Ty::U16 => ("UInt16".into(), None),
        Ty::U32 => ("UInt32".into(), None),
        Ty::U64 => ("UInt64".into(), None),
        Ty::I8 => ("Int8".into(), None),
        Ty::I16 => ("Int16".into(), None),
        Ty::I32 => ("Int32".into(), None),
        Ty::I64 => ("Int64".into(), None),
        Ty::Px => ("Int64".into(), Some("px".into())),
        Ty::Qty => ("Int64".into(), Some("qty".into())),
        Ty::Notional => ("Int64".into(), Some("notional".into())),
        Ty::Rate => ("Int64".into(), Some("rate".into())),
        Ty::Tsc => ("UInt64".into(), Some("tsc".into())),
        Ty::UtcNs => ("Int64".into(), Some("utc_ns".into())),
        Ty::Id(k, w) => (u(*w), Some(format!("id:{k}"))),
        Ty::Enum(n) => (
            u(enums.get(n).map_or(1, |e| e.width as u16)),
            Some(format!("enum:{n}")),
        ),
        Ty::Bits(n) => (
            u(enums.get(n).map_or(1, |e| e.width as u16)),
            Some(format!("bits:{n}")),
        ),
        Ty::Bytes(n) => (format!("FixedSizeBinary({n})"), None),
        Ty::Pad(_) | Ty::Nested(_) => (String::new(), None),
    }
}

fn arrow_fields(fields: &[Field], prefix: &str, enums: &BTreeMap<String, EnumTable>, out: &mut Vec<Value>) {
    for f in fields {
        let name = format!("{prefix}{}", f.name);
        match &f.ty {
            Ty::Pad(_) => {}
            Ty::Nested(inner) => arrow_fields(inner, &format!("{name}."), enums, out),
            ty => {
                let (t, hft) = arrow_type(ty, enums);
                let mut md = Map::new();
                if let Some(h) = hft {
                    md.insert("hft.type".into(), Value::String(h));
                }
                if f.measure {
                    md.insert("hft.measure".into(), Value::String("true".into()));
                }
                out.push(json!({ "name": name, "type": t, "nullable": false, "metadata": md }));
            }
        }
    }
}

/// `schemas/arrow/<kind>.json` of one kind.
pub fn arrow_json(k: &KindRow, ext: bool, enums: &BTreeMap<String, EnumTable>) -> String {
    let mut fields = Vec::new();
    arrow_fields(&k.fields, "", enums, &mut fields);
    let mut md = Map::new();
    md.insert("hft.kind".into(), Value::String(format!("0x{:04X}", k.kind)));
    md.insert("hft.name".into(), Value::String(k.name.clone()));
    md.insert(
        "hft.schema_version".into(),
        Value::String(k.schema_version.to_string()),
    );
    md.insert("hft.layout".into(), Value::String(k.layout.text()));
    if ext {
        md.insert("hft.origin".into(), Value::String("hft-ext-proto".into()));
    }
    let v = json!({ "fields": fields, "metadata": md });
    serde_json::to_string_pretty(&v).unwrap_or_default() + "\n"
}

/// `schemas/conn-reason.json`: `{"reasons": [{"code", "name", "state"}, …]}` in code order.
pub fn conn_reason_json(m: &Model) -> String {
    let rows: Vec<Value> = m
        .conn_reasons
        .iter()
        .map(|r| json!({ "code": r.code, "name": r.name, "state": r.state }))
        .collect();
    serde_json::to_string_pretty(&json!({ "reasons": rows })).unwrap_or_default()
        + "
"
}

// ---------- catalog

fn md_cell(s: &str) -> String {
    s.replace('|', "\\|").replace('\n', " ")
}

fn unit_of(ty: &Ty) -> &'static str {
    match ty {
        Ty::Px => "价格(资产 px_exp)",
        Ty::Qty => "数量(资产 qty_exp)",
        Ty::Notional => "名义额(1e-6,报价资产)",
        Ty::Rate => "比率(1e-9)",
        Ty::Tsc => "TSC",
        Ty::UtcNs => "UTC ns",
        _ => "",
    }
}

fn md_fields(s: &mut String, fields: &[Field], m: &Model) {
    s.push_str("| 偏移 | 字段 | 类型 | 单位 | 测量 | 说明 |\n|---|---|---|---|---|---|\n");
    let docs = doc_map(fields, "");
    for f in flatten(fields, &m.enums) {
        let doc = docs.get(&f.name).cloned().unwrap_or_default();
        let unit = unit_by_name(fields, &f.name);
        let meas = if measure_by_name(fields, &f.name) {
            "是"
        } else {
            ""
        };
        let _ = writeln!(
            s,
            "| {} | `{}` | `{}` | {} | {} | {} |",
            f.offset,
            f.name,
            f.ty,
            unit,
            meas,
            md_cell(&doc)
        );
    }
}

fn find_field<'a>(fields: &'a [Field], dotted: &str) -> Option<&'a Field> {
    let (head, rest) = match dotted.split_once('.') {
        Some((h, r)) => (h, Some(r)),
        None => (dotted, None),
    };
    let f = fields.iter().find(|f| f.name == head)?;
    match (rest, &f.ty) {
        (None, _) => Some(f),
        (Some(r), Ty::Nested(inner)) => find_field(inner, r),
        _ => None,
    }
}

fn unit_by_name(fields: &[Field], dotted: &str) -> &'static str {
    find_field(fields, dotted).map_or("", |f| unit_of(&f.ty))
}

fn measure_by_name(fields: &[Field], dotted: &str) -> bool {
    find_field(fields, dotted).is_some_and(|f| f.measure)
}

fn doc_map(fields: &[Field], prefix: &str) -> BTreeMap<String, String> {
    let mut out = BTreeMap::new();
    for f in fields {
        let n = format!("{prefix}{}", f.name);
        if let Ty::Nested(inner) = &f.ty {
            out.extend(doc_map(inner, &format!("{n}.")));
        }
        out.insert(n, f.doc.clone());
    }
    out
}

fn enums_used(fields: &[Field], out: &mut Vec<String>) {
    for f in fields {
        match &f.ty {
            Ty::Enum(n) | Ty::Bits(n) => {
                if !out.contains(n) {
                    out.push(n.clone());
                }
            }
            Ty::Nested(inner) => enums_used(inner, out),
            _ => {}
        }
    }
}

/// `docs/generated/event-catalog.md`.
pub fn catalog_md(m: &Model) -> String {
    let mut s = String::new();
    s += "<!-- Generated by `cargo xtask gen-schema`; do not edit. -->\n\n";
    s += "# 事件目录\n\n";
    s += "由 `cargo xtask gen-schema` 从 [hft-event](../../crates/hft-event/README.md) 的 Rust 定义(`schema::catalog()`)与 ";
    s += "[hft-refdata](../../crates/hft-refdata/README.md) 的码表生成;编号段、分类与演进规则见 [event-model](../subsystems/event-model.md)。";
    s += "类型写法与 `schemas/event-layout.lock` 相同;嵌套结构展开为 `外层.字段`。\n\n";
    s += "## kind\n\n";
    for (k, ext) in all_kinds(m) {
        let _ = writeln!(s, "### 0x{:04X} {}\n", k.kind, k.name);
        let _ = writeln!(s, "- 编号:`0x{:04X}`", k.kind);
        let _ = writeln!(s, "- 域:{}", k.domain);
        let _ = writeln!(s, "- 角色:{}", k.role);
        let _ = writeln!(s, "- 布局:{}", k.layout.text());
        let _ = writeln!(s, "- schema_version:{}", k.schema_version);
        let _ = writeln!(s, "- journal:{};CRC:{}", k.journals, k.crc);
        if k.optional {
            s += "- 可选扩展:链上\n";
        }
        if ext {
            s += "- 来源:hft-ext-proto\n";
        }
        if k.deprecated {
            s += "- 已废弃(仍可读)\n";
        }
        s += "\n";
        md_fields(&mut s, &k.fields, m);
        let mut used = Vec::new();
        enums_used(&k.fields, &mut used);
        if !used.is_empty() {
            s += "\n码表:";
            s += &used
                .iter()
                .map(|n| format!("[{n}](#码表-{})", n.to_lowercase()))
                .collect::<Vec<_>>()
                .join("、");
            s += "\n";
        }
        s += "\n";
    }
    s += "## 容器结构\n\n";
    for st in &m.structs {
        let _ = writeln!(s, "### {}\n\n- 大小:{}\n", st.name, st.size);
        md_fields(&mut s, &st.fields, m);
        s += "\n";
    }
    s += "## CmdKind\n\n| 编号 | 名 |\n|---|---|\n";
    for c in &m.cmd_kinds {
        let _ = writeln!(s, "| `0x{:04X}` | `{}` |", c.value, c.name);
    }
    s += "\n## Note 码\n\n";
    s += "引擎 Note 码登记表(`NOTE_NAMES`;名字、source 与默认级别)。`n` 取自 source 所在 crate 的 `NOTE_CODES` 表,尚无该表的 source 留空;";
    s += "策略码只在各策略的 schema JSON 中。\n\n| 码名 | source | n | 默认级别 | 登记的 v[] 字段 |\n|---|---|---|---|---|\n";
    for n in &m.notes {
        let code = m
            .note_consts
            .iter()
            .find(|c| c.name == n.name && c.source == n.source)
            .map_or(String::new(), |c| c.n.to_string());
        let v: Vec<String> =
            n.v.iter()
                .map(|(name, bit, bits)| format!("`{name}` [{bit}, +{bits})"))
                .collect();
        let _ = writeln!(
            s,
            "| `{}` | {} | {} | {} | {} |",
            n.name,
            n.source,
            code,
            n.level.as_deref().unwrap_or("按条件"),
            v.join("、")
        );
    }
    let extra: Vec<_> = m
        .note_consts
        .iter()
        .filter(|c| !m.notes.iter().any(|n| n.name == c.name))
        .collect();
    if !extra.is_empty() {
        s += "\n计数类码(只在 source crate 的 `NOTE_CODES` 表):\n\n| 码名 | source | n |\n|---|---|---|\n";
        for c in extra {
            let _ = writeln!(s, "| `{}` | {} | {} |", c.name, c.source, c.n);
        }
    }
    if !m.conn_reasons.is_empty() {
        s += "\n## ConnState.reason\n\n`Down`/`Rotated` 时为 hft-net `ErrBits` 原值,`Up`/`Alive` 时为 0;`Resync`/`Degraded` 取下表";
        s += "(唯一归属 [hft-venue](../../crates/hft-venue/README.md#产生与消费的事件) 的 `CONN_REASONS`)。\n\n| 码 | 名 | 状态 |\n|---|---|---|\n";
        for r in &m.conn_reasons {
            let _ = writeln!(s, "| {} | `{}` | {} |", r.code, r.name, r.state);
        }
    }
    s += "\n## LoadErrCode\n\n| 值 | 名 |\n|---|---|\n";
    for c in &m.load_err {
        let _ = writeln!(s, "| {} | `{}` |", c.value, c.name);
    }
    s += "\n## 码表\n\n";
    for e in m.enums.values() {
        let _ = writeln!(
            s,
            "### 码表 {}\n\n宽度 {} B。\n\n| 值 | 名 |\n|---|---|",
            e.name, e.width
        );
        for i in &e.items {
            let _ = writeln!(s, "| {} | `{}` |", i.value, i.name);
        }
        s += "\n";
    }
    s += "## 测量字段掩码\n\n| kind | 体内偏移 | 长度 |\n|---|---|---|\n";
    for (k, o, l) in &m.measure_mask {
        let _ = writeln!(s, "| `0x{k:04X}` | {o} | {l} |");
    }
    s
}

// ---------- hft-telemetry notes_catalog.rs

/// `crates/hft-telemetry/src/notes_catalog.rs`: one entry per `(source, n)` of the `NOTE_CODES` tables.
pub fn notes_rs(m: &Model) -> String {
    let mut s = String::new();
    s +=
        "//! Engine Note code table: `(source, n)` -> name, default level and the registered `v[]` fields.\n";
    s += "//! Generated by `cargo xtask gen-schema` from hft-event `NOTE_NAMES` and the source crates'\n";
    s += "//! `NOTE_CODES` tables; do not edit. Strategy codes are not in this table.\n\n";
    s += "/// One engine Note code.\n#[derive(Copy, Clone, Debug)]\npub struct NoteEntry {\n";
    s += "    /// `source << 24 | n`.\n    pub code: u32,\n    /// `NoteSource` value.\n    pub source: u8,\n    pub n: u32,\n";
    s += "    pub name: &'static str,\n    /// Default `NoteLevel` value; 0 = by condition or owned by the source crate.\n    pub level: u8,\n";
    s += "    /// `(name, bit, bits)` of the `v[]` fields listed in the registry.\n    pub v: &'static [(&'static str, u16, u16)],\n}\n\n";
    s += "pub static NOTES_CATALOG: &[NoteEntry] = &[\n";
    let mut rows: Vec<_> = m
        .note_consts
        .iter()
        .map(|c| (note_source_value(&c.source).unwrap_or(0), c.n, c))
        .collect();
    rows.sort_by_key(|(src, n, _)| (*src, *n));
    rows.dedup_by_key(|(src, n, _)| (*src, *n));
    for (src, n, c) in rows {
        let reg = m.notes.iter().find(|r| r.name == c.name);
        let level = reg
            .and_then(|r| r.level.as_deref())
            .and_then(note_level_value)
            .unwrap_or(0);
        let v: Vec<String> = reg
            .map(|r| {
                r.v.iter()
                    .map(|(name, bit, bits)| format!("(\"{name}\", {bit}, {bits})"))
                    .collect()
            })
            .unwrap_or_default();
        let _ = writeln!(
            s,
            "    NoteEntry {{ code: 0x{:08X}, source: {src}, n: {n}, name: \"{}\", level: {level}, v: &[{}] }},",
            (src << 24) | n,
            c.name,
            v.join(", ")
        );
    }
    s += "];\n";
    s
}

/// Every generated file (path → content) except the lock.
pub fn outputs(m: &Model) -> BTreeMap<String, String> {
    let mut out = BTreeMap::new();
    out.insert(EVENTS_PY.to_string(), events_py(m));
    out.insert(REFDATA_PY.to_string(), refdata_py(m));
    out.insert(CATALOG_MD.to_string(), catalog_md(m));
    out.insert(NOTES_RS.to_string(), notes_rs(m));
    if !m.conn_reasons.is_empty() {
        out.insert(CONN_REASON_JSON.to_string(), conn_reason_json(m));
    }
    for (k, ext) in all_kinds(m) {
        out.insert(arrow_path(&k.name), arrow_json(k, ext, &m.enums));
    }
    out
}
