//! `schemas/event-layout.lock`: rendering, parsing and the append-only comparison
//! (failure conditions: crates/hft-event/README.md "实现说明").

use std::collections::BTreeMap;
use std::fmt::Write as _;

use super::model::{
    Code, EnumTable, Field, KindRow, LOCK_STRUCTS, Model, Strategies, StrategyRow, Ty, note_source_value,
};

/// Lock file path, relative to the repo root.
pub const LOCK_PATH: &str = "schemas/event-layout.lock";

/// One flattened field: nested structs expand to `outer.inner` with absolute offsets.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct Flat {
    pub offset: u16,
    pub name: String,
    pub ty: String,
    pub width: u16,
    pub pad: bool,
    /// Code field whose table has no 0 value.
    pub zero_illegal: bool,
}

/// Flattens `fields` (nested structs inlined) in offset order.
pub fn flatten(fields: &[Field], enums: &BTreeMap<String, EnumTable>) -> Vec<Flat> {
    let mut out = Vec::new();
    flatten_into(fields, enums, "", 0, &mut out);
    out.sort_by_key(|f| f.offset);
    out
}

fn flatten_into(
    fields: &[Field],
    enums: &BTreeMap<String, EnumTable>,
    prefix: &str,
    base: u16,
    out: &mut Vec<Flat>,
) {
    for f in fields {
        let name = format!("{prefix}{}", f.name);
        match &f.ty {
            Ty::Nested(inner) => flatten_into(inner, enums, &format!("{name}."), base + f.offset, out),
            ty => out.push(Flat {
                offset: base + f.offset,
                ty: ty.text(),
                width: ty.width(enums),
                pad: matches!(ty, Ty::Pad(_)),
                zero_illegal: matches!(ty, Ty::Enum(n) if enums.get(n).is_some_and(EnumTable::zero_illegal)),
                name,
            }),
        }
    }
}

/// A kind as recorded in the lock.
#[derive(Clone, Debug, Default)]
pub struct LockKind {
    pub kind: u16,
    pub name: String,
    pub version: u16,
    /// `fixed` / `var` / `multi`.
    pub class: String,
    /// Body or prefix size.
    pub size: u16,
    pub deprecated: bool,
    pub ext: bool,
    pub fields: Vec<Flat>,
}

/// A struct as recorded in the lock.
#[derive(Clone, Debug, Default)]
pub struct LockStruct {
    pub name: String,
    pub size: u16,
    pub fields: Vec<Flat>,
}

/// A parsed lock file.
#[derive(Clone, Debug, Default)]
pub struct Lock {
    pub kinds: Vec<LockKind>,
    pub cmds: Vec<Code>,
    pub load_errs: Vec<Code>,
    /// `(source, n, name)`.
    pub notes: Vec<(String, u32, String)>,
    pub structs: Vec<LockStruct>,
    pub strategies: Vec<StrategyRow>,
}

fn layout_words(k: &KindRow) -> String {
    let mut s = format!(
        "0x{:04X} {} v{} {}",
        k.kind,
        k.name,
        k.schema_version,
        k.layout.text()
    );
    if k.deprecated {
        s += " deprecated";
    }
    s
}

fn push_fields(s: &mut String, flats: &[Flat]) {
    for f in flats {
        let _ = writeln!(s, "  {} {} {}", f.offset, f.name, f.ty);
    }
}

/// Renders the lock of `m`; when strategies were not exported, `baseline`'s strategy rows are kept.
pub fn render(m: &Model, baseline: Option<&Lock>) -> String {
    let mut s = String::new();
    s += "# Generated by `cargo xtask gen-schema`; do not edit.\n";
    s += "# Append-only baseline; failure conditions: crates/hft-event/README.md#实现说明\n";
    s += "lock-format 1\n";
    let mut kinds: Vec<(&KindRow, bool)> = m.kinds.iter().map(|k| (k, false)).collect();
    if let Some(ext) = &m.ext_kinds {
        kinds.extend(ext.iter().map(|k| (k, true)));
    }
    kinds.sort_by_key(|(k, _)| k.kind);
    for (k, ext) in kinds {
        let _ = writeln!(s, "kind {}{}", layout_words(k), if ext { " ext" } else { "" });
        push_fields(&mut s, &flatten(&k.fields, &m.enums));
    }
    let mut cmds = m.cmd_kinds.clone();
    cmds.sort_by_key(|c| c.value);
    for c in &cmds {
        let _ = writeln!(s, "cmd 0x{:04X} {}", c.value, c.name);
    }
    let mut le = m.load_err.clone();
    le.sort_by_key(|c| c.value);
    for c in &le {
        let _ = writeln!(s, "load-err {} {}", c.value, c.name);
    }
    let mut notes: Vec<_> = m
        .note_consts
        .iter()
        .map(|c| {
            (
                note_source_value(&c.source).unwrap_or(u32::MAX),
                c.source.clone(),
                c.n,
                c.name.clone(),
            )
        })
        .collect();
    notes.sort();
    notes.dedup();
    for (_, src, n, name) in &notes {
        let _ = writeln!(s, "note {src} {n} {name}");
    }
    for name in LOCK_STRUCTS {
        if let Some(st) = m.structs.iter().find(|x| x.name == *name) {
            let _ = writeln!(s, "struct {} {}", st.name, st.size);
            push_fields(&mut s, &flatten(&st.fields, &m.enums));
        }
    }
    let strategies: Vec<StrategyRow> = match &m.strategies {
        Strategies::Exported(v) => v.clone(),
        Strategies::Skipped(_) => baseline.map(|b| b.strategies.clone()).unwrap_or_default(),
    };
    for st in &strategies {
        let _ = writeln!(s, "strategy {} {}", st.kind_id, st.name);
        let mut rows: Vec<(&str, &Code)> = Vec::new();
        rows.extend(st.notes.iter().map(|c| ("note", c)));
        rows.extend(st.ops.iter().map(|c| ("op", c)));
        rows.extend(st.tags.iter().map(|c| ("tag", c)));
        for (w, c) in rows {
            let _ = writeln!(s, "  {w} {} {}", c.value, c.name);
        }
    }
    s
}

fn num(s: &str) -> Option<u32> {
    match s.strip_prefix("0x") {
        Some(h) => u32::from_str_radix(h, 16).ok(),
        None => s.parse().ok(),
    }
}

/// Width of a lock type text (code tables: unknown here, 0; only reserved-byte widths are used).
fn type_width(ty: &str) -> u16 {
    match ty {
        "u8" | "i8" | "id:venue" | "id:account" | "id:strategy" | "id:conn" => 1,
        "u16" | "i16" | "id:asset" | "id:kind" => 2,
        "u32" | "i32" | "id:inst" | "id:group" | "id:slot" => 4,
        t if t.starts_with("enum:") || t.starts_with("bits:") => 0,
        t => t.rsplit(':').next().and_then(|n| n.parse().ok()).unwrap_or(8),
    }
}

enum Cur {
    None,
    Kind,
    Struct,
    Strategy,
}

/// Parses a lock file; `Err` = malformed line (line number and text).
pub fn parse(text: &str) -> Result<Lock, String> {
    let mut l = Lock::default();
    let mut cur = Cur::None;
    for (i, raw) in text.lines().enumerate() {
        let line = raw.trim_end();
        if line.trim().is_empty() || line.trim_start().starts_with('#') {
            continue;
        }
        let bad = || format!("{}:{}: cannot parse '{}'", LOCK_PATH, i + 1, line);
        let w: Vec<&str> = line.split_whitespace().collect();
        if line.starts_with("  ") {
            match cur {
                Cur::Kind | Cur::Struct => {
                    let [off, name, ty] = w[..] else { return Err(bad()) };
                    let flat = Flat {
                        offset: off.parse().map_err(|_| bad())?,
                        name: name.to_string(),
                        ty: ty.to_string(),
                        width: type_width(ty),
                        pad: ty.starts_with("pad:"),
                        zero_illegal: false,
                    };
                    match cur {
                        Cur::Kind => l.kinds.last_mut().ok_or_else(bad)?.fields.push(flat),
                        _ => l.structs.last_mut().ok_or_else(bad)?.fields.push(flat),
                    }
                }
                Cur::Strategy => {
                    let [what, v, name] = w[..] else { return Err(bad()) };
                    let c = Code::new(num(v).ok_or_else(bad)?, name);
                    let st = l.strategies.last_mut().ok_or_else(bad)?;
                    match what {
                        "note" => st.notes.push(c),
                        "op" => st.ops.push(c),
                        "tag" => st.tags.push(c),
                        _ => return Err(bad()),
                    }
                }
                Cur::None => return Err(bad()),
            }
            continue;
        }
        match w.first().copied() {
            Some("lock-format") => cur = Cur::None,
            Some("kind") => {
                if w.len() < 6 {
                    return Err(bad());
                }
                let class = w[4].to_string();
                let size: u16 = w[5].parse().map_err(|_| bad())?;
                let rest = if class == "var" {
                    &w[7.min(w.len())..]
                } else {
                    &w[6..]
                };
                l.kinds.push(LockKind {
                    kind: num(w[1]).ok_or_else(bad)? as u16,
                    name: w[2].to_string(),
                    version: w[3]
                        .strip_prefix('v')
                        .and_then(|v| v.parse().ok())
                        .ok_or_else(bad)?,
                    class,
                    size,
                    deprecated: rest.contains(&"deprecated"),
                    ext: rest.contains(&"ext"),
                    fields: Vec::new(),
                });
                cur = Cur::Kind;
            }
            Some("cmd") if w.len() == 3 => {
                l.cmds.push(Code::new(num(w[1]).ok_or_else(bad)?, w[2]));
                cur = Cur::None;
            }
            Some("load-err") if w.len() == 3 => {
                l.load_errs.push(Code::new(num(w[1]).ok_or_else(bad)?, w[2]));
                cur = Cur::None;
            }
            Some("note") if w.len() == 4 => {
                l.notes
                    .push((w[1].to_string(), num(w[2]).ok_or_else(bad)?, w[3].to_string()));
                cur = Cur::None;
            }
            Some("struct") if w.len() == 3 => {
                l.structs.push(LockStruct {
                    name: w[1].to_string(),
                    size: w[2].parse().map_err(|_| bad())?,
                    fields: Vec::new(),
                });
                cur = Cur::Struct;
            }
            Some("strategy") if w.len() == 3 => {
                l.strategies.push(StrategyRow {
                    kind_id: num(w[1]).ok_or_else(bad)?,
                    name: w[2].to_string(),
                    notes: Vec::new(),
                    ops: Vec::new(),
                    tags: Vec::new(),
                });
                cur = Cur::Strategy;
            }
            _ => return Err(bad()),
        }
    }
    Ok(l)
}

/// Prefix-extension check of one body / prefix / struct. Returns `(errors, changed, reserved_only)`:
/// `changed` = the field table or size differs; `reserved_only` = the only change is named fields in
/// formerly reserved bytes at the same size.
fn compare_fields(
    label: &str,
    old: &[Flat],
    old_size: u16,
    new: &[Flat],
    new_size: u16,
) -> (Vec<String>, bool, bool) {
    let mut errs = Vec::new();
    let mut appended_named = false;
    let mut occupied = false;
    let mut accounted = vec![false; new.len()];
    for o in old.iter().filter(|o| !o.pad) {
        match new.iter().position(|n| n.name == o.name) {
            Some(i) => {
                let n = &new[i];
                accounted[i] = true;
                if n.offset != o.offset {
                    errs.push(format!(
                        "{label}: field `{}` moved from offset {} to {} (new layout is not a prefix extension)",
                        o.name, o.offset, n.offset
                    ));
                } else if n.ty != o.ty {
                    errs.push(format!(
                        "{label}: field `{}` retyped {} -> {}",
                        o.name, o.ty, n.ty
                    ));
                }
            }
            None => match new.iter().find(|n| n.offset == o.offset && !n.pad) {
                Some(n) => errs.push(format!(
                    "{label}: field `{}` at offset {} renamed or replaced by `{}`",
                    o.name, o.offset, n.name
                )),
                None => errs.push(format!(
                    "{label}: field `{}` (offset {}) removed",
                    o.name, o.offset
                )),
            },
        }
    }
    for o in old.iter().filter(|o| o.pad) {
        let (lo, hi) = (o.offset, o.offset + o.width);
        for (i, n) in new.iter().enumerate() {
            let (nlo, nhi) = (n.offset, n.offset + n.width);
            if nhi <= lo || nlo >= hi || accounted[i] {
                continue;
            }
            if nlo < lo || nhi > hi {
                if !n.pad {
                    errs.push(format!(
                        "{label}: field `{}` at offset {} crosses the reserved bytes {}..{} (`{}`)",
                        n.name, n.offset, lo, hi, o.name
                    ));
                }
                accounted[i] = true;
                continue;
            }
            accounted[i] = true;
            if !n.pad {
                occupied = true;
                if n.zero_illegal {
                    errs.push(format!(
                        "{label}: field `{}` occupies reserved bytes but its type {} has no 0 value",
                        n.name, n.ty
                    ));
                }
            }
        }
    }
    for (i, n) in new.iter().enumerate() {
        if accounted[i] {
            continue;
        }
        if n.offset >= old_size {
            if !n.pad {
                appended_named = true;
                if n.zero_illegal {
                    errs.push(format!(
                        "{label}: appended field `{}` has type {} with no 0 value (old readers zero-fill it)",
                        n.name, n.ty
                    ));
                }
            }
        } else if !n.pad {
            errs.push(format!(
                "{label}: field `{}` inserted inside the old body at offset {} (only tail appends are allowed)",
                n.name, n.offset
            ));
        } else if !old
            .iter()
            .any(|o| o.pad && o.offset <= n.offset && n.offset < o.offset + o.width)
        {
            errs.push(format!(
                "{label}: reserved bytes `{}` inserted inside the old body at offset {}",
                n.name, n.offset
            ));
        }
    }
    if new_size < old_size {
        errs.push(format!("{label}: size shrank from {old_size} to {new_size} B"));
    }
    let same = |a: &Flat, b: &Flat| a.offset == b.offset && a.name == b.name && a.ty == b.ty;
    let changed =
        new_size != old_size || old.len() != new.len() || old.iter().zip(new).any(|(a, b)| !same(a, b));
    let reserved_only = changed && new_size == old_size && !appended_named && occupied && errs.is_empty();
    (errs, changed, reserved_only)
}

/// New numbers below the largest baseline number of the same space that the baseline does not list:
/// a retired or reserved number taken again (numbers are assigned in increasing order).
fn gap_reuse(
    what: &str,
    fmt: &dyn Fn(u32) -> String,
    old: &[u32],
    new: &[(u32, &str)],
    errs: &mut Vec<String>,
) {
    let Some(max) = old.iter().max() else { return };
    for (v, name) in new {
        if v < max && !old.contains(v) {
            errs.push(format!(
                "{what} {} `{name}` takes a retired or reserved number (new numbers must be > {})",
                fmt(*v),
                fmt(*max)
            ));
        }
    }
}

/// Compares two `(number, name)` lists: numbers never vanish and are never reused.
fn compare_codes(
    what: &str,
    fmt: &dyn Fn(u32) -> String,
    old: &[Code],
    new: &[Code],
    errs: &mut Vec<String>,
) {
    for o in old {
        match new.iter().find(|n| n.value == o.value) {
            None => errs.push(format!(
                "{what} {} `{}` disappeared (numbers never vanish)",
                fmt(o.value),
                o.name
            )),
            Some(n) if n.name != o.name => errs.push(format!(
                "{what} {} reused: `{}` -> `{}` (numbers are never reused)",
                fmt(o.value),
                o.name,
                n.name
            )),
            Some(_) => {}
        }
    }
}

fn hex4(v: u32) -> String {
    format!("0x{v:04X}")
}

fn dec(v: u32) -> String {
    v.to_string()
}

/// Append-only comparison of `m` with the baseline lock; returns the violations.
pub fn compare(base: &Lock, m: &Model) -> Vec<String> {
    let mut errs = Vec::new();
    let mut kinds: Vec<&KindRow> = m.kinds.iter().collect();
    if let Some(ext) = &m.ext_kinds {
        kinds.extend(ext.iter());
    }
    for o in &base.kinds {
        let Some(n) = kinds.iter().find(|k| k.kind == o.kind) else {
            errs.push(format!(
                "kind 0x{:04X} `{}` disappeared (numbers never vanish)",
                o.kind, o.name
            ));
            continue;
        };
        if n.name != o.name {
            errs.push(format!(
                "kind 0x{:04X} reused: `{}` -> `{}` (numbers are never reused)",
                o.kind, o.name, n.name
            ));
            continue;
        }
        let label = format!("kind 0x{:04X} {}", o.kind, o.name);
        if n.layout.class() != o.class {
            errs.push(format!(
                "{label}: layout class changed {} -> {}",
                o.class,
                n.layout.class()
            ));
            continue;
        }
        let flats = flatten(&n.fields, &m.enums);
        let (mut e, changed, reserved_only) =
            compare_fields(&label, &o.fields, o.size, &flats, n.layout.size());
        // A PR can contain several compatible additions since its merge base. Each
        // addition advances the version; comparing the endpoints must allow all of them.
        if changed && !reserved_only && n.schema_version <= o.version {
            e.push(format!(
                "{label}: layout changed but schema_version {} -> {} (must exceed {})",
                o.version, n.schema_version, o.version
            ));
        } else if n.schema_version < o.version {
            e.push(format!(
                "{label}: schema_version decreased {} -> {}",
                o.version, n.schema_version
            ));
        }
        errs.extend(e);
    }
    for seg in 0..=0xFFu16 {
        let old: Vec<u32> = base
            .kinds
            .iter()
            .filter(|k| k.kind >> 8 == seg && !k.ext)
            .map(|k| k.kind as u32)
            .collect();
        let new: Vec<(u32, &str)> = m
            .kinds
            .iter()
            .filter(|k| k.kind >> 8 == seg)
            .map(|k| (k.kind as u32, k.name.as_str()))
            .collect();
        gap_reuse("kind", &hex4, &old, &new, &mut errs);
    }
    compare_codes("CmdKind", &hex4, &base.cmds, &m.cmd_kinds, &mut errs);
    let new: Vec<(u32, &str)> = m.cmd_kinds.iter().map(|c| (c.value, c.name.as_str())).collect();
    gap_reuse(
        "CmdKind",
        &hex4,
        &base.cmds.iter().map(|c| c.value).collect::<Vec<_>>(),
        &new,
        &mut errs,
    );
    compare_codes("LoadErrCode", &dec, &base.load_errs, &m.load_err, &mut errs);
    let new: Vec<(u32, &str)> = m.load_err.iter().map(|c| (c.value, c.name.as_str())).collect();
    gap_reuse(
        "LoadErrCode",
        &dec,
        &base.load_errs.iter().map(|c| c.value).collect::<Vec<_>>(),
        &new,
        &mut errs,
    );
    for (src, n, name) in &base.notes {
        match m.note_consts.iter().find(|c| &c.source == src && c.n == *n) {
            None => errs.push(format!(
                "engine Note code ({src}, {n}) `{name}` disappeared (numbers never vanish)"
            )),
            Some(c) if &c.name != name => errs.push(format!(
                "engine Note code ({src}, {n}) reused: `{name}` -> `{}` (numbers are never reused)",
                c.name
            )),
            Some(_) => {}
        }
    }
    for o in &base.structs {
        let Some(n) = m.structs.iter().find(|s| s.name == o.name) else {
            errs.push(format!("struct {} disappeared", o.name));
            continue;
        };
        let (e, _, _) = compare_fields(
            &format!("struct {}", o.name),
            &o.fields,
            o.size,
            &flatten(&n.fields, &m.enums),
            n.size,
        );
        errs.extend(e);
    }
    if let Strategies::Exported(new) = &m.strategies {
        for o in &base.strategies {
            let id = format!("kind_id {} (0x{:04X})", o.kind_id, o.kind_id);
            let Some(n) = new.iter().find(|s| s.kind_id == o.kind_id) else {
                errs.push(format!(
                    "strategy {id} `{}` disappeared (numbers never vanish)",
                    o.name
                ));
                continue;
            };
            if n.name != o.name {
                errs.push(format!(
                    "strategy {id} reused: `{}` -> `{}` (numbers are never reused)",
                    o.name, n.name
                ));
                continue;
            }
            let k = o.kind_id;
            compare_codes(
                &format!("strategy {id}:"),
                &|v| format!("({k}, Note {v})"),
                &o.notes,
                &n.notes,
                &mut errs,
            );
            compare_codes(
                &format!("strategy {id}:"),
                &|v| format!("({k}, op {v})"),
                &o.ops,
                &n.ops,
                &mut errs,
            );
            compare_codes(
                &format!("strategy {id}:"),
                &|v| format!("({k}, tag {v})"),
                &o.tags,
                &n.tags,
                &mut errs,
            );
        }
    }
    errs
}
